// Draws Clawd's pictures from the points of hooks/lib/clawd.ts and writes them to hooks/lib/cat-art.ts, as base64 PNGs, for the band's `Image`.
//
//   bun mods/tokenomics/tools/clawd/make-clawd.ts            writes hooks/lib/cat-art.ts
//   bun mods/tokenomics/tools/clawd/make-clawd.ts out.png    also lays every picture out on a sheet, to look at
//
// Run it again after the points change: the cells of a terminal come from the points at once, the pictures only from here.
import { writeFileSync } from 'node:fs'
import { FRAME_ROWS, type Frame, MARK_COLORS, POINTS_H, POINTS_W, POINT_COLORS, type Row } from '../../hooks/lib/clawd.ts'
import { png } from './png.ts'

/** The pixels a point is drawn with: a cell is 16 x 32, as wide as half its height, as a cell of a terminal is. */
const PX_W = 8
const PX_H = 16
const OUT_W = POINTS_W * PX_W
const OUT_H = POINTS_H * PX_H

/** The letters and signs of the marks, as bitmaps (a `#` is a pixel of the bitmap, drawn `scale` pixels across and down). */
const STAMPS: Record<string, { bitmap: string[]; scaleX: number; scaleY: number }> = {
  z: { bitmap: ['###', '..#', '.#.', '#..', '###'], scaleX: 4, scaleY: 5 },
  Z: { bitmap: ['###', '..#', '.#.', '#..', '###'], scaleX: 5, scaleY: 6 },
  '+': { bitmap: ['.#.', '###', '.#.'], scaleX: 4, scaleY: 8 },
  '*': { bitmap: ['#.#', '.#.', '#.#'], scaleX: 4, scaleY: 8 },
}

const rgbaOf = (color: number): [number, number, number, number] => [(color >> 16) & 255, (color >> 8) & 255, color & 255, 255]

/** A picture as RGBA, on a clear ground. */
const draw = (frame: Frame): Uint8Array => {
  const rgba = new Uint8Array(OUT_W * OUT_H * 4)
  const paint = (x: number, y: number, color: number): void => {
    if (x < 0 || x >= OUT_W || y < 0 || y >= OUT_H) return
    rgba.set(rgbaOf(color), (y * OUT_W + x) * 4)
  }
  frame.points.forEach((line, y) =>
    [...line].forEach((letter, x) => {
      const color = POINT_COLORS[letter as keyof typeof POINT_COLORS]
      if (color === undefined) return
      for (let j = 0; j < PX_H; j++) for (let i = 0; i < PX_W; i++) paint(x * PX_W + i, y * PX_H + j, color)
    }),
  )
  for (const mark of frame.marks) {
    const stamp = STAMPS[mark.ch]
    if (stamp === undefined) throw new Error(`no bitmap for the mark ${mark.ch}`)
    // Centred in its cell, two points across and two down.
    const x0 = Math.round(mark.col * 2 * PX_W + (2 * PX_W - stamp.bitmap[0]!.length * stamp.scaleX) / 2)
    const y0 = Math.round(mark.row * 2 * PX_H + (2 * PX_H - stamp.bitmap.length * stamp.scaleY) / 2)
    stamp.bitmap.forEach((line, r) =>
      [...line].forEach((ch, c) => {
        if (ch !== '#') return
        for (let j = 0; j < stamp.scaleY; j++) for (let i = 0; i < stamp.scaleX; i++) paint(x0 + c * stamp.scaleX + i, y0 + r * stamp.scaleY + j, MARK_COLORS[mark.color])
      }),
    )
  }
  return rgba
}

const rows = Object.keys(FRAME_ROWS) as Row[]
const pictures = rows.flatMap(row => FRAME_ROWS[row].map((frame, index) => ({ row, index, rgba: draw(frame) })))
const lines = pictures.map(p => `  '${p.row}:${p.index}':\n    '${Buffer.from(png(OUT_W, OUT_H, p.rgba)).toString('base64')}',`)
writeFileSync(
  new URL('../../hooks/lib/cat-art.ts', import.meta.url),
  `// Generated by tools/clawd/make-clawd.ts from hooks/lib/clawd.ts: Clawd's pictures, each a PNG of ${OUT_W} x ${OUT_H} pixels in base64,
// by row (${rows.join(', ')}) and place in the row. Do not edit.
export const CAT_PNG: Readonly<Record<string, string>> = {
${lines.join('\n')}
}
`,
)
console.log(pictures.length, 'pictures,', lines.join('').length, 'characters')

const out = process.argv[2]
if (out !== undefined) {
  const cols = Math.max(...rows.map(row => FRAME_ROWS[row].length))
  const pad = 8
  const w = cols * (OUT_W + pad) + pad
  const h = rows.length * (OUT_H + pad) + pad
  const sheet = new Uint8Array(w * h * 4)
  for (let i = 0; i < w * h; i++) sheet.set([30, 30, 34, 255], i * 4)
  for (const p of pictures) {
    const ox = pad + p.index * (OUT_W + pad)
    const oy = pad + rows.indexOf(p.row) * (OUT_H + pad)
    for (let y = 0; y < OUT_H; y++) {
      for (let x = 0; x < OUT_W; x++) {
        const a = p.rgba[(y * OUT_W + x) * 4 + 3]! / 255
        const o = ((oy + y) * w + ox + x) * 4
        for (let c = 0; c < 3; c++) sheet[o + c] = Math.round(p.rgba[(y * OUT_W + x) * 4 + c]! * a + sheet[o + c]! * (1 - a))
      }
    }
  }
  writeFileSync(out, png(w, h, sheet))
}
