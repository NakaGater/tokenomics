// Cuts the cat's pictures out of sheet.png and writes them to hooks/lib/cat-art.ts, as base64 PNGs, for the band's `Image`.
//
//   bun mods/tokenomics/tools/cat/make-cat.ts            writes hooks/lib/cat-art.ts
//   bun mods/tokenomics/tools/cat/make-cat.ts out.png    also lays every picture out on a sheet, to look at
//
// sheet.png is five rows of six cats on a dark ground: run, walk, sweat, sleep, jump (slice.ts says how it is cut).
import { readFileSync, writeFileSync } from 'node:fs'
import { png } from './png.ts'
import { OUT_H, OUT_W, ROWS, playlists, slice } from './slice.ts'

const frames = playlists(slice(readFileSync(new URL('./sheet.png', import.meta.url))))
const counts = Object.fromEntries(ROWS.map(row => [row, frames.filter(f => f.row === row).length]))
const lines = frames.map(f => `  '${f.row}:${f.index}':\n    '${Buffer.from(png(f.w, f.h, f.rgba)).toString('base64')}',`)
writeFileSync(
  new URL('../../hooks/lib/cat-art.ts', import.meta.url),
  `// Generated by tools/cat/make-cat.ts from tools/cat/sheet.png: the cat's pictures, each a PNG of ${OUT_W} x ${OUT_H} pixels in base64,
// by row (run, walk, sweat, sleep, jump) and place in the play order of the row. Do not edit.
export const CAT_COUNTS = ${JSON.stringify(counts)} as const

export const CAT_PNG: Readonly<Record<string, string>> = {
${lines.join('\n')}
}
`,
)
console.log(frames.length, 'pictures,', lines.join('').length, 'characters')

const out = process.argv[2]
if (out !== undefined) {
  const cols = Math.max(...Object.values(counts)), pad = 8, w = cols * (OUT_W + pad) + pad, h = ROWS.length * (OUT_H + pad) + pad
  const sheet = new Uint8Array(w * h * 4)
  for (let i = 0; i < w * h; i++) { sheet[i * 4] = 30; sheet[i * 4 + 1] = 30; sheet[i * 4 + 2] = 30; sheet[i * 4 + 3] = 255 }
  for (const f of frames) {
    const ox = pad + f.index * (OUT_W + pad), oy = pad + ROWS.indexOf(f.row) * (OUT_H + pad)
    for (let y = 0; y < OUT_H; y++) for (let x = 0; x < OUT_W; x++) {
      const a = f.rgba[(y * OUT_W + x) * 4 + 3]! / 255
      const o = ((oy + y) * w + ox + x) * 4
      for (let c = 0; c < 3; c++) sheet[o + c] = Math.round(f.rgba[(y * OUT_W + x) * 4 + c]! * a + 30 * (1 - a))
    }
  }
  writeFileSync(out, png(w, h, sheet))
}
